def load_quality_reports():

    conn = get_database_connection()

    try:
        df = pd.read_sql_query(
            """
            SELECT *
            FROM quality_reports
            ORDER BY report_id DESC
            """,
            conn
        )
    except Exception:
        try:
            df = pd.read_sql_query(
                """
                SELECT *
                FROM quality_reports
                ORDER BY id DESC
                """,
                conn
            )
        except Exception:
            df = pd.DataFrame()

    conn.close()

    return df


