def load_dataset(filename):

    file_path = DATA_PATH / filename

    if file_path.exists():
        try:
            return pd.read_csv(file_path)
        except Exception:
            return pd.DataFrame()

    return pd.DataFrame()


# =========================================================
# STATUS HELPERS
# =========================================================

def status_icon(status):

    if status == "HEALTHY":
        return "🟢"

    if status == "WARNING":
        return "🟡"

    if status == "CRITICAL":
        return "🔴"

    return "⚪"


def get_status(value, warning_threshold, critical_threshold):

    if value <= critical_threshold:
        return "CRITICAL"

    if value <= warning_threshold:
        return "WARNING"

    return "HEALTHY"


def get_completeness_score(df):

    if df.empty:
        return 0.0

    total_cells = df.shape[0] * df.shape[1]

    if total_cells == 0:
        return 0.0

    missing_cells = int(df.isnull().sum().sum())

    return round(
        (1 - missing_cells / total_cells) * 100,
        2
    )


def get_duplicate_rate(df):

    if df.empty:
        return 0.0

    duplicate_rows = int(df.duplicated().sum())

    return round(
        (duplicate_rows / len(df)) * 100,
        2
    )


# =========================================================
# SCHEMA VALIDATION
# =========================================================

def validate_schema(df, filename):

    # Expected customer schema generated by DataSentinel
    expected_columns = [
        "customer_id",
        "name",
        "email",
        "city",
        "state",
        "signup_date",
        "age"
    ]

    # Only validate the customer datasets against
    # the known customer schema.
    if "customer" not in filename.lower():
        return {
            "status": "N/A",
            "missing": [],
            "unexpected": []
        }

    actual_columns = list(df.columns)

    missing_columns = [
        column
        for column in expected_columns
        if column not in actual_columns
    ]

    unexpected_columns = [
        column
        for column in actual_columns
        if column not in expected_columns
    ]

    if missing_columns:
        status = "CRITICAL"

    elif unexpected_columns:
        status = "WARNING"

    else:
        status = "HEALTHY"

    return {
        "status": status,
        "missing": missing_columns,
        "unexpected": unexpected_columns
    }


# =========================================================
# ANOMALY DETECTION
# =========================================================

def calculate_anomaly_rate(df):

    if df.empty:
        return 0.0

    numeric_columns = df.select_dtypes(
        include=np.number
    ).columns.tolist()

    if not numeric_columns:
        return 0.0

    anomaly_indices = set()

    # IQR-based anomaly detection
    for column in numeric_columns:

        series = df[column].dropna()

        if len(series) < 10:
            continue

        q1 = series.quantile(0.25)
        q3 = series.quantile(0.75)

        iqr = q3 - q1

        if iqr == 0:
            continue

        lower_bound = q1 - 1.5 * iqr
        upper_bound = q3 + 1.5 * iqr

        anomalies = df[
            (df[column] < lower_bound) |
            (df[column] > upper_bound)
        ]

        anomaly_indices.update(
            anomalies.index.tolist()
        )

    anomaly_count = len(anomaly_indices)

    return round(
        (anomaly_count / len(df)) * 100,
        2
    )


# =========================================================
# OVERALL QUALITY SCORE
# =========================================================

def calculate_quality_score(
    completeness,
    duplicate_rate,
    schema_status,
    anomaly_rate
):

    completeness_score = completeness

    duplicate_score = max(
        0,
        100 - duplicate_rate * 10
    )

    anomaly_score = max(
        0,
        100 - anomaly_rate * 10
    )

    if schema_status == "CRITICAL":
        schema_score = 0

    elif schema_status == "WARNING":
        schema_score = 50

    elif schema_status == "HEALTHY":
        schema_score = 100

    else:
        schema_score = 100

    score = (
        completeness_score * 0.35
        + duplicate_score * 0.25
        + schema_score * 0.20
        + anomaly_score * 0.20
    )

    return round(score, 2)


def overall_status(
    completeness,
    duplicate_rate,
    schema_status,
    anomaly_rate
):

    if schema_status == "CRITICAL":
        return "CRITICAL"

    if completeness < 95:
        return "CRITICAL"

    if duplicate_rate >= 5:
        return "CRITICAL"

    if anomaly_rate >= 5:
        return "CRITICAL"

    if completeness < 99:
        return "WARNING"

    if duplicate_rate > 0:
        return "WARNING"

    if anomaly_rate > 0:
        return "WARNING"

    if schema_status == "WARNING":
        return "WARNING"

    return "HEALTHY"


